-- CIS konnekt — исправление: проверка свободного никнейма при регистрации
--
-- Баг: политика profiles_select_authenticated разрешала читать профили
-- только вошедшим в аккаунт — а проверка "свободен ли никнейм" на экране
-- регистрации происходит ДО входа (роль anon), поэтому проверка всегда
-- молча считала любой никнейм свободным. Настоящую защиту от дубликатов
-- при этом давал только уникальный индекс в базе — отсюda непонятная
-- ошибка вместо "никнейм занят".
--
-- Исправление — разрешить читать профили (имя, никнейм, фото) вообще
-- всем, включая анонимных посетителей, как уже сделано для событий и
-- организаторов. В профилях нет ничего чувствительного.

drop policy "profiles_select_authenticated" on public.profiles;

create policy "profiles_select_all" on public.profiles
  for select using (true);

grant select on public.profiles to anon;
